const messages: Record<Language, Record<MessageKey, string>> = { id, en };
const activeLanguage = ref<Language>("id");

export function setLanguage(language: Language): void {
  activeLanguage.value = language;
  document.documentElement.lang = language;
}

export function translate(key: MessageKey, values: Record<string, string | number> = {}): string {
  let message = messages[activeLanguage.value][key];
  for (const [name, value] of Object.entries(values)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function useI18n() {
  return {
    language: readonly(activeLanguage),
    t: translate,
    isEnglish: computed(() => activeLanguage.value === "en"),
  };
}

export type { MessageKey };
